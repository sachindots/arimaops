// Findings reports and exports, all from the one Finding schema (docs/core-model.md section 5).
// Pure: same findings in, same text out. HackerOne and Bugcrowd exports are for pasting by hand;
// nothing is ever submitted. The HTML report prints to PDF from the browser.

import type { Finding } from "../src/data/model";
import { SEVERITIES, type Scope, type Severity } from "../src/data/types";
import { BRAND } from "../src/data/brand";

export const EXPORT_FORMATS = ["markdown", "json", "sarif", "html", "hackerone", "bugcrowd"] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

export interface ReportInput {
  project: string;
  scope: Scope | undefined;
  findings: Finding[];
  name: (id: string) => string;
  generatedAt: string;
}

const rank = (s: Severity) => SEVERITIES.indexOf(s);
/** Reported findings, most severe first; false positives are left out of every export but the Markdown appendix. */
const live = (fs: Finding[]) => fs.filter((f) => f.status !== "false-positive").sort((a, b) => rank(a.severity) - rank(b.severity) || a.id.localeCompare(b.id));
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const where = (f: Finding) => (f.location ? `${f.location.file}${f.location.startLine ? `:${f.location.startLine}` : ""}` : f.asset.value);
const scoreText = (f: Finding) => (f.cvss ? `CVSS 4.0 ${f.cvss.score.toFixed(1)} (${f.cvss.vector})` : "not scored");
const ids = (label: string, list: string[]) => (list.length ? [`- **${label}:** ${list.join(", ")}`] : []);
const fence = (text: string) => {
  const ticks = "`".repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  return [ticks, text, ticks];
};
const evidenceMd = (f: Finding) => (f.evidence.length ? f.evidence.flatMap((e) => [`_${e.kind}_`, "", ...fence(e.content), ""]) : ["_none_", ""]);

export function renderMarkdown(r: ReportInput): string {
  const shown = live(r.findings);
  const count = (s: Severity) => shown.filter((f) => f.severity === s).length;
  const lines = [
    `# Security report: ${r.project}`,
    "",
    `_Generated by ${BRAND.name} on ${r.generatedAt.slice(0, 10)} from its saved findings. Edit findings in ${BRAND.name}, not here._`,
    "",
    "## Scope",
    "",
    `- In scope: ${r.scope?.inScope.join(", ") || "(not set)"}`,
    `- Out of scope: ${r.scope?.outOfScope.join(", ") || "(none)"}`,
    ...(r.scope?.rules ? ["", "Rules of engagement:", "", r.scope.rules] : []),
    "",
    "## Summary",
    "",
    "| Severity | Count |",
    "| --- | --- |",
    ...SEVERITIES.map((s) => `| ${s} | ${count(s)} |`),
    "",
    "## Findings",
    "",
  ];
  if (!shown.length) lines.push("No findings yet.", "");
  for (const f of shown)
    lines.push(
      `### ${f.id}: ${f.title}`,
      "",
      `- **Severity:** ${f.severity} · ${scoreText(f)}`,
      `- **Status:** ${f.status}${f.verified ? ` · verified${f.verifiedBy ? ` by ${r.name(f.verifiedBy)}` : ""}` : " · not verified"}`,
      `- **Asset:** \`${where(f)}\` (${f.asset.kind})`,
      ...(f.ssvc ? [`- **SSVC:** ${f.ssvc.decision} (exploitation ${f.ssvc.exploitation}, automatable ${f.ssvc.automatable ? "yes" : "no"}, technical impact ${f.ssvc.technicalImpact})`] : []),
      ...ids("CWE", f.cwe),
      ...ids("ATT&CK", f.attack),
      ...ids("D3FEND", f.d3fend),
      ...(f.wstg ? [`- **WSTG:** ${f.wstg}`] : []),
      `- **Reported by:** ${r.name(f.reporterId)}${f.taskId ? ` (task ${f.taskId})` : ""}, ${f.at.slice(0, 10)}`,
      "",
      "**Description**",
      "",
      f.description || "_none_",
      "",
      ...(f.impact ? ["**Impact**", "", f.impact, ""] : []),
      "**Evidence**",
      "",
      ...evidenceMd(f),
      "**Remediation**",
      "",
      f.remediation || "_none_",
      "",
    );
  const fp = r.findings.filter((f) => f.status === "false-positive");
  if (fp.length) lines.push("## Ruled out (false positives)", "", ...fp.map((f) => `- ${f.id}: ${f.title} (\`${where(f)}\`)`), "");
  return lines.join("\n");
}

export function renderJson(r: ReportInput): string {
  return JSON.stringify({ project: r.project, generatedAt: r.generatedAt, scope: r.scope ?? null, findings: live(r.findings) }, null, 2);
}

const SARIF_LEVEL: Record<Severity, "error" | "warning" | "note"> = { critical: "error", high: "error", medium: "warning", low: "note", info: "note" };

/** SARIF 2.1.0: one rule per finding (findings are distinct issues, not repeated checks). */
export function renderSarif(r: ReportInput): string {
  const shown = live(r.findings);
  const sarif = {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [
      {
        tool: {
          driver: {
            name: BRAND.name,
            informationUri: "https://github.com/sachindots/arimaops",
            rules: shown.map((f) => ({
              id: f.id,
              name: f.title,
              shortDescription: { text: f.title },
              fullDescription: { text: f.description || f.title },
              ...(f.remediation ? { help: { text: f.remediation } } : {}),
              properties: {
                tags: ["security", ...f.cwe, ...f.attack],
                ...(f.cvss ? { "security-severity": f.cvss.score.toFixed(1) } : {}),
              },
            })),
          },
        },
        results: shown.map((f, i) => ({
          ruleId: f.id,
          ruleIndex: i,
          level: SARIF_LEVEL[f.severity],
          message: { text: `${f.title}${f.impact ? `. ${f.impact}` : ""}` },
          locations: [
            f.location
              ? {
                  physicalLocation: {
                    artifactLocation: { uri: f.location.file },
                    ...(f.location.startLine ? { region: { startLine: f.location.startLine, ...(f.location.endLine ? { endLine: f.location.endLine } : {}) } } : {}),
                  },
                }
              : { logicalLocations: [{ name: f.asset.value, kind: f.asset.kind }] },
          ],
          properties: { severity: f.severity, status: f.status, verified: f.verified, ...(f.cvss ? { cvssVector: f.cvss.vector } : {}) },
        })),
      },
    ],
  };
  return JSON.stringify(sarif, null, 2);
}

const unverified = (f: Finding) => (f.verified ? [] : ["> Not verified yet. Check it before submitting.", ""]);

/** HackerOne's report form, field by field, one section per finding. */
export function renderHackerOne(r: ReportInput): string {
  return live(r.findings)
    .flatMap((f) => [
      `## ${f.id}: ${f.title}`,
      "",
      ...unverified(f),
      `**Asset:** ${where(f)}`,
      `**Weakness:** ${f.cwe.join(", ") || "(choose one)"}`,
      `**Severity:** ${cap(f.severity)}${f.cvss ? ` · ${f.cvss.vector}` : ""}`,
      "",
      "### Summary",
      "",
      f.description || "_none_",
      "",
      "### Steps to reproduce",
      "",
      ...evidenceMd(f),
      "### Impact",
      "",
      f.impact || "_none_",
      "",
      ...(f.remediation ? ["### Suggested fix", "", f.remediation, ""] : []),
      "---",
      "",
    ])
    .join("\n");
}

/** Bugcrowd's submission form, field by field, one section per finding. Pick the VRT category by hand. */
export function renderBugcrowd(r: ReportInput): string {
  return live(r.findings)
    .flatMap((f) => [
      `## ${f.id}: ${f.title}`,
      "",
      ...unverified(f),
      `**Summary title:** ${f.title}`,
      `**Target:** ${f.asset.value}`,
      `**Vulnerability type (VRT):** choose in Bugcrowd${f.cwe.length ? ` (${f.cwe.join(", ")})` : ""}`,
      `**URL / location:** ${where(f)}`,
      `**Severity:** ${cap(f.severity)}${f.cvss ? ` · CVSS 4.0 ${f.cvss.score.toFixed(1)}` : ""}`,
      "",
      "### Description",
      "",
      f.description || "_none_",
      "",
      "### Proof of concept",
      "",
      ...evidenceMd(f),
      "### Impact",
      "",
      f.impact || "_none_",
      "",
      ...(f.remediation ? ["### Suggested fix", "", f.remediation, ""] : []),
      "---",
      "",
    ])
    .join("\n");
}

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A standalone page that prints cleanly: the browser's Print → Save as PDF makes the PDF report. */
export function renderHtml(r: ReportInput): string {
  const shown = live(r.findings);
  const row = (label: string, value: string) => (value ? `<tr><th>${label}</th><td>${esc(value)}</td></tr>` : "");
  const body = shown
    .map(
      (f) => `<section class="finding sev-${f.severity}">
<h2>${esc(f.id)}: ${esc(f.title)}</h2>
<table>${row("Severity", `${cap(f.severity)} · ${scoreText(f)}`)}${row("Status", `${f.status}${f.verified ? " · verified" : " · not verified"}`)}${row("Asset", `${where(f)} (${f.asset.kind})`)}${row("SSVC", f.ssvc ? f.ssvc.decision : "")}${row("CWE", f.cwe.join(", "))}${row("ATT&CK", f.attack.join(", "))}${row("D3FEND", f.d3fend.join(", "))}${row("WSTG", f.wstg ?? "")}${row("Reported by", `${r.name(f.reporterId)}, ${f.at.slice(0, 10)}`)}</table>
<h3>Description</h3><p>${esc(f.description || "none")}</p>
${f.impact ? `<h3>Impact</h3><p>${esc(f.impact)}</p>` : ""}
<h3>Evidence</h3>${f.evidence.map((e) => `<p class="kind">${esc(e.kind)}</p><pre>${esc(e.content)}</pre>`).join("") || "<p>none</p>"}
<h3>Remediation</h3><p>${esc(f.remediation || "none")}</p>
</section>`,
    )
    .join("\n");
  const counts = SEVERITIES.map((s) => `<td>${shown.filter((f) => f.severity === s).length}</td>`).join("");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Security report: ${esc(r.project)}</title>
<style>
body { font: 15px/1.5 system-ui, sans-serif; color: #111; background: #fff; max-width: 860px; margin: 24px auto; padding: 0 16px; }
h1 { font-size: 26px; } h2 { font-size: 19px; margin-top: 0; } h3 { font-size: 15px; margin-bottom: 4px; }
table { border-collapse: collapse; margin: 8px 0; } th, td { border: 1px solid #ccc; padding: 4px 8px; text-align: left; vertical-align: top; }
pre { background: #f4f4f4; padding: 8px; white-space: pre-wrap; word-break: break-word; font-size: 12px; }
.finding { border-top: 4px solid #999; padding-top: 12px; margin-top: 24px; break-inside: avoid-page; }
.sev-critical { border-color: #b00020; } .sev-high { border-color: #e65100; } .sev-medium { border-color: #f9a825; } .sev-low { border-color: #2e7d32; }
.kind { font-style: italic; margin: 8px 0 0; } .muted { color: #555; }
@media print { body { margin: 0; max-width: none; } a { color: inherit; } }
</style></head><body>
<h1>Security report: ${esc(r.project)}</h1>
<p class="muted">Generated by ${esc(BRAND.name)} on ${esc(r.generatedAt.slice(0, 10))}. Print this page and choose Save as PDF for a PDF.</p>
<h2>Scope</h2>
<table>${row("In scope", r.scope?.inScope.join(", ") || "(not set)")}${row("Out of scope", r.scope?.outOfScope.join(", ") || "(none)")}${row("Rules", r.scope?.rules ?? "")}</table>
<h2>Summary</h2>
<table><tr>${SEVERITIES.map((s) => `<th>${s}</th>`).join("")}</tr><tr>${counts}</tr></table>
${body || "<p>No findings yet.</p>"}
</body></html>
`;
}

export const RENDER: Record<ExportFormat, { render: (r: ReportInput) => string; type: string; ext: string }> = {
  markdown: { render: renderMarkdown, type: "text/markdown; charset=utf-8", ext: "md" },
  json: { render: renderJson, type: "application/json", ext: "json" },
  sarif: { render: renderSarif, type: "application/sarif+json", ext: "sarif" },
  html: { render: renderHtml, type: "text/html; charset=utf-8", ext: "html" },
  hackerone: { render: renderHackerOne, type: "text/markdown; charset=utf-8", ext: "hackerone.md" },
  bugcrowd: { render: renderBugcrowd, type: "text/markdown; charset=utf-8", ext: "bugcrowd.md" },
};

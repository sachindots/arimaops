// Security findings for an engagement: agents file them with the Team MCP tool report_finding (in-scope
// targets only); you and the lead triage them. Saved in <repo>/.arima/arima.db (findings.json row) and rendered to
// <repo>/deliverables/security-report.md on every change, so the report is versioned with the repo.

import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { repoDirOf } from "./paths";
import { dirname, join } from "node:path";
import { FINDING_STATUSES, SEVERITIES, type Finding, type FindingStatus, type Severity } from "../src/data/types";
import type { Hub } from "./hub";
import { log } from "./lib/log";
import { checkScope } from "./scope";
import { readDoc, writeDoc } from "./lib/docs";

const REPORT = join("deliverables", "security-report.md");
const clip = (v: unknown, n: number) => String(v ?? "").trim().slice(0, n);

function atomicWrite(file: string, text: string) {
  mkdirSync(dirname(file), { recursive: true });
  const tmp = `${file}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
}

/** The report: summary by severity, then each finding (most severe first). Pure, so it's testable. */
export function renderReport(project: string, scope: { inScope: string[]; outOfScope: string[]; rules: string } | undefined, findings: Finding[], name: (id: string) => string): string {
  const live = findings.filter((f) => f.status !== "false-positive");
  const order = (f: Finding) => SEVERITIES.indexOf(f.severity);
  const sorted = [...live].sort((a, b) => order(a) - order(b) || a.id.localeCompare(b.id));
  const count = (s: Severity) => live.filter((f) => f.severity === s).length;
  const lines = [
    `# Security report: ${project}`,
    "",
    `_Generated by .hq from its saved findings. Edit findings in HQ, not here._`,
    "",
    "## Scope",
    "",
    `- In scope: ${scope?.inScope.join(", ") || "(not set)"}`,
    `- Out of scope: ${scope?.outOfScope.join(", ") || "(none)"}`,
    ...(scope?.rules ? ["", "Rules of engagement:", "", scope.rules] : []),
    "",
    "## Summary",
    "",
    "| Severity | Count |",
    "| --- | --- |",
    ...SEVERITIES.map((s) => `| ${s} | ${count(s)} |`),
    "",
    "## Findings",
    "",
  ];
  if (!sorted.length) lines.push("No findings yet.", "");
  for (const f of sorted)
    lines.push(
      `### ${f.id}: ${f.title}`,
      "",
      `- **Severity:** ${f.severity}  ·  **Status:** ${f.status}  ·  **Target:** \`${f.target}\``,
      `- **Reported by:** ${name(f.reporterId)}${f.taskId ? ` (task ${f.taskId})` : ""}, ${f.at.slice(0, 10)}`,
      "",
      "**Description**",
      "",
      f.description || "_none_",
      "",
      "**Evidence**",
      "",
      "```",
      f.evidence || "(none)",
      "```",
      "",
      "**Remediation**",
      "",
      f.remediation || "_none_",
      "",
    );
  const fp = findings.filter((f) => f.status === "false-positive");
  if (fp.length) lines.push("## Ruled out (false positives)", "", ...fp.map((f) => `- ${f.id}: ${f.title} (\`${f.target}\`)`), "");
  return lines.join("\n");
}

export class Findings {
  private file: string;

  constructor(private hub: Hub) {
    this.file = join(repoDirOf(hub.repo.root), "findings.json");
    try {
      hub.snap.findings = readDoc<Finding[]>(this.file) ?? [];
    } catch (err) {
      log.warn(`couldn't read ${this.file}: ${err instanceof Error ? err.message : err}`);
      hub.snap.findings = [];
    }
  }

  private get list(): Finding[] {
    return (this.hub.snap.findings ??= []);
  }

  private save(f: Finding) {
    writeDoc(this.file, this.list);
    const { name, scope } = this.hub.snap.config.project;
    atomicWrite(join(this.hub.repo.root, REPORT), renderReport(name, scope, this.list, (id) => this.hub.name(id)));
    this.hub.emit({ type: "finding.updated", finding: { ...f } });
  }

  /** From an agent. Refused when the project isn't a security engagement or the target is out of scope. */
  report(reporterId: string, taskId: string | null, input: { title?: unknown; severity?: unknown; target?: unknown; description?: unknown; evidence?: unknown; remediation?: unknown }): Finding {
    const project = this.hub.snap.config.project;
    if (!this.hub.snap.config.rules.findings) throw new Error("This project isn't a security engagement, so findings aren't tracked here. Write it as a deliverable instead.");
    const target = clip(input.target, 300);
    const s = checkScope(project.scope, target);
    if (!s.ok) {
      this.hub.activity("scope.refused", reporterId, `${this.hub.name(reporterId)} tried to report on ${target || "an unnamed target"}: refused, ${s.why}`);
      throw new Error(`Not recorded: ${s.why} Only report findings on in-scope targets.`);
    }
    const title = clip(input.title, 160);
    if (!title) throw new Error("Give the finding a short title.");
    const severity = SEVERITIES.includes(input.severity as Severity) ? (input.severity as Severity) : "info";
    const n = Math.max(0, ...this.list.map((f) => Number(f.id.slice(2)) || 0)) + 1;
    const now = new Date().toISOString();
    const f: Finding = {
      id: `F-${String(n).padStart(3, "0")}`, title, severity, target,
      description: clip(input.description, 8000), evidence: clip(input.evidence, 16000), remediation: clip(input.remediation, 4000),
      status: "open", reporterId, taskId, at: now, updatedAt: now,
    };
    this.list.push(f);
    this.save(f);
    this.hub.activity(severity === "critical" || severity === "high" ? "agent.needs-input" : "message", reporterId, `${this.hub.name(reporterId)} reported ${f.id} (${severity}): ${title}`);
    return f;
  }

  /** From you or the lead: status, severity or text. */
  update(id: string, patch: { status?: unknown; severity?: unknown; title?: unknown; remediation?: unknown }): Finding {
    const f = this.list.find((x) => x.id === id);
    if (!f) throw new Error(`No finding ${id}.`);
    if (FINDING_STATUSES.includes(patch.status as FindingStatus)) f.status = patch.status as FindingStatus;
    if (SEVERITIES.includes(patch.severity as Severity)) f.severity = patch.severity as Severity;
    if (typeof patch.title === "string" && patch.title.trim()) f.title = clip(patch.title, 160);
    if (typeof patch.remediation === "string") f.remediation = clip(patch.remediation, 4000);
    f.updatedAt = new Date().toISOString();
    this.save(f);
    return f;
  }
}

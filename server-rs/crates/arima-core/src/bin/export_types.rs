    #[test]
    fn renders_clean_self_contained_typescript() {
        let ts = render_typescript();
        assert!(ts.starts_with("// SPDX-License-Identifier: AGPL-3.0-or-later"));
        assert!(!ts.contains("\nimport "));
        for expected in [
            "export type AgentCli",
            "export const AGENT_CLIS",
            "export type ServerRole",
            "export type MeetingKind",
            "export type MeetingSession",
            "export type MeetingTurn",
            "export type MeetingMinutes",
            "export type VoiceProvider",
            "export type VisualDecision",
            "export type DecisionPayload",
            "export type PackAgent",
            "export type PackEntry",
            "export type FormPayload",
            "export type VisualFeedback",
            "export type FeedbackRoute",
            "export type OutboxMessage",
            "export type WsClientMessage",
            "export type WsCommandAck",
            "export type WsServerEvent",
        ] {
            assert!(ts.contains(expected), "missing {expected} in generated TS:\n{ts}");
        }
    }


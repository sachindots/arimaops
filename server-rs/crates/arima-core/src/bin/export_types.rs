//! Exports all `arima-core` TypeScript contract declarations into a single self-contained `.ts` file.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use arima_core::{
    AgentCli, AgentInstruction, AuditEntry, AuthUser, BoundingBox, ConsoleErrorEntry, DecisionKind,
    DecisionPayload, DecisionStatus, DeviceSession, ElementSelection, FeedbackRoute, FormAnswer,
    FormPayload, FormSpec,
    MeetingAgendaItem, MeetingKind, MeetingMinutes, MeetingSession, MeetingStatus, MeetingTurn,
    MeetingUrgency, OpinionSide, OutboxMessage, OutboxMessageKind, PackAgent, PackApproval, PackChange, PackEntry, PackFileSummary, PackLock, PackScan, PackSkill, PackSource, PackToolServer, PasskeyInfo, PermissionPayload,
    PreviewMode, PreviewTarget, PreviewTargetStatus, ProjectRole, ProposedDecision, ProposedTask,
    QuestionAnswer, QuestionOption, QuestionPayload, QuestionPrompt, SecondOpinionPayload,
    ServerRole, ToolServer, ToolServerCheck, ToolServerSource, ToolServerTransport, VisualDecision, VisualFeedback, VoiceProvider, WsClientMessage, WsCommandAck,
    WsServerEvent,
};
use ts_rs::{Config, TS};

fn push_decl<T: TS>(out: &mut String) {
    let decl = T::decl(&Config::default());
    let trimmed = decl.trim();
    if trimmed.starts_with("export ") {
        out.push_str(trimmed);
    } else {
        out.push_str("export ");
        out.push_str(trimmed);
    }
    out.push_str("\n\n");
}

pub fn render_typescript() -> String {
    let mut out = String::from(
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n\
         // Generated by arima-core export_types — do not edit by hand.\n\n\
         export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n",
    );

    // Auth & RBAC
    push_decl::<AgentCli>(&mut out);
    let cli_list: Vec<String> = AgentCli::ALL.iter().map(|c| format!("\"{}\"", c.id())).collect();
    out.push_str(&format!("export const AGENT_CLIS = [{}] as const;\n\n", cli_list.join(", ")));
    push_decl::<ServerRole>(&mut out);
    push_decl::<ProjectRole>(&mut out);
    push_decl::<AuthUser>(&mut out);
    push_decl::<DeviceSession>(&mut out);
    push_decl::<PasskeyInfo>(&mut out);
    push_decl::<AuditEntry>(&mut out);

    // Discussion Sessions, Meetings & Standup Calls (before DecisionPayload & WsServerEvent)
    push_decl::<MeetingKind>(&mut out);
    push_decl::<MeetingStatus>(&mut out);
    push_decl::<MeetingUrgency>(&mut out);
    push_decl::<VoiceProvider>(&mut out);
    push_decl::<MeetingAgendaItem>(&mut out);
    push_decl::<MeetingTurn>(&mut out);
    push_decl::<ProposedTask>(&mut out);
    push_decl::<ProposedDecision>(&mut out);
    push_decl::<AgentInstruction>(&mut out);
    push_decl::<MeetingMinutes>(&mut out);
    push_decl::<MeetingSession>(&mut out);

    // Unified Visual Decisions
    push_decl::<DecisionStatus>(&mut out);
    push_decl::<DecisionKind>(&mut out);
    push_decl::<QuestionOption>(&mut out);
    push_decl::<QuestionPrompt>(&mut out);
    push_decl::<QuestionAnswer>(&mut out);
    push_decl::<QuestionPayload>(&mut out);
    push_decl::<OpinionSide>(&mut out);
    push_decl::<SecondOpinionPayload>(&mut out);
    push_decl::<PermissionPayload>(&mut out);
    push_decl::<PackAgent>(&mut out);
    push_decl::<PackChange>(&mut out);
    push_decl::<PackFileSummary>(&mut out);
    push_decl::<FormSpec>(&mut out);
    push_decl::<FormAnswer>(&mut out);
    push_decl::<FormPayload>(&mut out);
    push_decl::<DecisionPayload>(&mut out);
    push_decl::<VisualDecision>(&mut out);

    // Isolated Preview & Tablet Visual Feedback
    push_decl::<PreviewMode>(&mut out);
    push_decl::<PreviewTargetStatus>(&mut out);
    push_decl::<PreviewTarget>(&mut out);
    push_decl::<BoundingBox>(&mut out);
    push_decl::<ElementSelection>(&mut out);
    push_decl::<ConsoleErrorEntry>(&mut out);
    push_decl::<FeedbackRoute>(&mut out);
    push_decl::<VisualFeedback>(&mut out);

    // Durable Outbox
    push_decl::<OutboxMessageKind>(&mut out);
    push_decl::<OutboxMessage>(&mut out);

    // Tool servers, one list per project
    push_decl::<ToolServerTransport>(&mut out);
    push_decl::<ToolServerSource>(&mut out);
    push_decl::<ToolServerCheck>(&mut out);
    push_decl::<ToolServer>(&mut out);
    push_decl::<PackSource>(&mut out);
    push_decl::<PackSkill>(&mut out);
    push_decl::<PackToolServer>(&mut out);
    push_decl::<PackScan>(&mut out);
    push_decl::<PackApproval>(&mut out);
    push_decl::<PackEntry>(&mut out);
    push_decl::<PackLock>(&mut out);

    // Correlated WS Protocol
    push_decl::<WsClientMessage>(&mut out);
    push_decl::<WsCommandAck>(&mut out);
    push_decl::<WsServerEvent>(&mut out);

    out
}

fn write_atomic(dest: &Path, content: &str) -> std::io::Result<()> {
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }
    let tmp = dest.with_extension("ts.tmp");
    {
        let mut f = fs::File::create(&tmp)?;
        f.write_all(content.as_bytes())?;
        f.sync_all()?;
    }
    fs::rename(tmp, dest)?;
    Ok(())
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let dest = env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("src/data/generated.ts"));
    let ts = render_typescript();
    write_atomic(&dest, &ts)?;
    let catalog = serde_json::to_string_pretty(&arima_core::form::catalog_json())? + "\n";
    write_atomic(&dest.with_file_name("form-catalog.json"), &catalog)?;
    Ok(())
}

